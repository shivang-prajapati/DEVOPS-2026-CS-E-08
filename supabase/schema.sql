create extension if not exists pgcrypto;

create table if not exists public.users (
  id uuid primary key default gen_random_uuid(),
  name text not null,
  email text not null unique check (email = lower(email)),
  password_hash text not null,
  role text not null default 'client' check (role in ('admin', 'agent', 'manager', 'client')),
  created_at timestamptz not null default now()
);

create table if not exists public.contacts (
  id bigint generated by default as identity primary key,
  name text not null,
  email text not null,
  subject text,
  message text not null,
  created_at timestamptz not null default now()
);

create table if not exists public.enquiries (
  id bigint generated by default as identity primary key,
  name text not null,
  email text not null,
  phone text,
  property_id text,
  message text not null,
  created_at timestamptz not null default now()
);

create table if not exists public.properties (
  id bigint generated by default as identity primary key,
  title text not null unique,
  price text not null,
  type text not null,
  location text not null,
  image text,
  created_at timestamptz not null default now()
);

alter table public.users enable row level security;
alter table public.contacts enable row level security;
alter table public.enquiries enable row level security;
alter table public.properties enable row level security;

revoke all on public.users, public.contacts, public.enquiries, public.properties from anon, authenticated;
grant all on public.users, public.contacts, public.enquiries, public.properties to service_role;
grant usage, select on all sequences in schema public to service_role;

